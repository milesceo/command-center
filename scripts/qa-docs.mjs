// Renders the manual test checklist (apps/desktop/src/qa/checklist.ts) to docs/TESTING.md.
//   node --experimental-strip-types scripts/qa-docs.mjs          write the file
//   node --experimental-strip-types scripts/qa-docs.mjs --check  fail if the file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'docs', 'TESTING.md');
const { QA_ITEMS, QA_AREAS, AREA_LABELS, CHECKLIST_VERSION } = await import(
  pathToFileURL(join(root, 'apps/desktop/src/qa/checklist.ts')).href
);

const NEEDS = {
  any: 'anywhere',
  'windows-desktop': 'the Windows desktop app',
  'real-login': 'a real login or API key',
  network: 'a network connection',
};

const lines = [
  '# Manual testing',
  '',
  '<!-- Generated by `pnpm qa:docs` from apps/desktop/src/qa/checklist.ts. Do not edit by hand. -->',
  '',
  'This is everything automation cannot confirm. It is the same list the app shows in its **QA',
  'checklist** panel (Ctrl+Shift+Q, or Settings > About > QA checklist panel). Use the panel: each',
  'item has a one-click setup, Pass / Fail / Skip, and a button that opens a prefilled GitHub issue.',
  '',
  '## How the process works',
  '',
  '1. A change that automation cannot fully verify adds its items to `checklist.ts` and lists their',
  '   IDs under **Needs your eyes** in the pull request. `pnpm qa:docs` refreshes this file.',
  '2. You open the panel, work through "Not tested", and answer each item.',
  '3. A failure becomes a GitHub issue (labels `qa-failure`, `needs-triage`, `area:*`) through the',
  "   panel's **Report on GitHub** button; you review it and press Submit on GitHub.",
  '4. A fix references the issue. Items whose question changed get a new `rev`, which clears the old',
  '   answer. **Copy results** puts a Markdown report on the clipboard.',
  '',
  `Checklist version ${CHECKLIST_VERSION}, ${QA_ITEMS.length} items.`,
  '',
];

for (const area of QA_AREAS) {
  const items = QA_ITEMS.filter((i) => i.area === area);
  if (items.length === 0) continue;
  lines.push(`## ${AREA_LABELS[area]}`, '');
  for (const item of items) {
    lines.push(`### ${item.id}: ${item.title}`, '');
    lines.push(
      `Needs ${NEEDS[item.needs]}.${item.destructive ? ' **Erases local data.**' : ''}${item.setup ? ` Panel setup: \`${item.setup}\`.` : ''}`,
      '',
    );
    item.steps.forEach((step, index) => lines.push(`${index + 1}. ${step}`));
    lines.push('', `**Expected:** ${item.expected}`, '');
  }
}

const text = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error('docs/TESTING.md is out of date. Run: pnpm qa:docs');
    process.exit(1);
  }
  console.log('docs/TESTING.md is up to date.');
} else {
  writeFileSync(target, text, 'utf8');
  console.log(`wrote docs/TESTING.md (${QA_ITEMS.length} items)`);
}
