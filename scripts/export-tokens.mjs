// Exports the app's design tokens (colors per theme, and every palette) as DTCG-style JSON that a
// Figma variables importer (Tokens Studio, or Figma's own import) can read, so a Figma file and
// the running app share one source of truth.
//   node --experimental-strip-types scripts/export-tokens.mjs          write docs/design/tokens.json
//   node --experimental-strip-types scripts/export-tokens.mjs --check  fail if it is stale
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'docs', 'design', 'tokens.json');
const css = readFileSync(join(root, 'apps/desktop/src/styles/index.css'), 'utf8');
const { PALETTES, paletteTokens, ACCENT_SWATCHES } = await import(
  pathToFileURL(join(root, 'apps/desktop/src/lib/appearance.ts')).href
);

/** Custom properties declared in the first rule whose selector contains `selector`. */
function declarations(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`selector not found: ${selector}`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  const out = {};
  for (const match of css.slice(open + 1, close).matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    out[match[1]] = match[2].trim();
  }
  return out;
}

const dark = declarations(":root,\n[data-theme='dark']");
const light = { ...dark, ...declarations("[data-theme='light']") };

const COLOR = /^#[0-9a-f]{6}$/i;
const group = (tokens) =>
  Object.fromEntries(
    Object.entries(tokens)
      .filter(([, value]) => COLOR.test(value))
      .map(([name, value]) => [name, { $type: 'color', $value: value.toLowerCase() }]),
  );

const doc = {
  $description:
    'Geeked design tokens. Generated by scripts/export-tokens.mjs from styles/index.css and lib/appearance.ts; do not edit by hand.',
  themes: { dark: group(dark), light: group(light) },
  palettes: Object.fromEntries(
    PALETTES.map((palette) => [
      palette.id,
      {
        label: palette.label,
        dark: group(paletteTokens(palette.id, null, 'dark')),
        light: group(paletteTokens(palette.id, null, 'light')),
      },
    ]),
  ),
  accentSwatches: ACCENT_SWATCHES.map((value) => ({ $type: 'color', $value: value })),
  radii: { control: '6px', panel: '10px' },
  fonts: { sans: 'Geist Variable', mono: 'Geist Mono Variable' },
};

const text = `${JSON.stringify(doc, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error('docs/design/tokens.json is out of date. Run: pnpm design:tokens');
    process.exit(1);
  }
  console.log('docs/design/tokens.json is up to date.');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text, 'utf8');
  console.log(
    `wrote docs/design/tokens.json (${Object.keys(doc.themes.dark).length} tokens per theme)`,
  );
}
